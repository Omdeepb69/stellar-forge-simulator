_ALIAS = {"—": "-", "–": "-", "’": "'", "“": '"', "”": '"', "…": "."}
HEIGHT = 8
LINE = 10


def _rows(ch: str) -> list[str]:
    g = _G.get(ch) or _G.get(_ALIAS.get(ch, "")) or _G.get(ch.upper()) or _G["?"]
    rows = g.split("|")
    return rows + ["." * len(rows[0])] * (HEIGHT - len(rows))


def char_width(ch: str) -> int:
    return len(_rows(ch)[0])


@lru_cache(maxsize=8192)
def width(msg: str, scale: int = 2) -> int:
    if not msg:
        return 0
    return (sum(char_width(c) + 1 for c in msg) - 1) * scale


@lru_cache(maxsize=2048)
def _glyph(ch: str, color: tuple, scale: int) -> pygame.Surface:
    rows = _rows(ch)
    w = len(rows[0])
    s = pygame.Surface((w, HEIGHT), pygame.SRCALPHA)
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                s.set_at((x, y), color)
    return pygame.transform.scale(s, (w * scale, HEIGHT * scale)) if scale != 1 else s


@lru_cache(maxsize=1024)
def render(msg: str, color: tuple, scale: int = 2, shadow: tuple | None = (12, 10, 20),
           outline: tuple | None = None) -> pygame.Surface:
    """``shadow``: 1-px drop shadow. ``outline``: full 1-px outline (for text over the world)."""
    pad = scale if outline else 0
    w = width(msg, scale) + scale + 2 * pad
    surf = pygame.Surface((max(1, w), HEIGHT * scale + scale + 2 * pad), pygame.SRCALPHA)
    layers = []
    if outline:
        layers += [(outline, (dx * scale + pad, dy * scale + pad)) for dx in (-1, 0, 1) for dy in (-1, 0, 1)
                   if dx or dy]
        layers += [(outline, (pad, pad + scale))]
    elif shadow:
        layers.append((shadow, (scale, scale)))
    layers.append((color, (pad, pad)))
    for col, (ox, oy) in layers:
        x = 0
        for ch in msg:
            g = _glyph(ch, tuple(col), scale)
            surf.blit(g, (x + ox, oy))
            x += g.get_width() + scale
    return surf


def draw(surf, msg, pos, scale: int = 2, color=(235, 240, 250), anchor: str = "topleft", shadow=(12, 10, 20),
         outline=None):
    img = render(str(msg), tuple(color), scale, shadow, tuple(outline) if outline else None)
    r = img.get_rect(**{anchor: (int(pos[0]), int(pos[1]))})
    surf.blit(img, r)
    return r


def wrap(msg: str, max_width: int, scale: int = 2) -> list[str]:
    lines, cur = [], ""
    for word in msg.split():
        trial = f"{cur} {word}".strip()
        if width(trial, scale) > max_width and cur:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines
